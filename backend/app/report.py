"""
RouteLens Lite - Report Generation

Assembles what was actually observed into something a student can keep.

A report is not a screenshot. It records:
- what was measured, and when
- the evidence behind each claim, with its source
- what was simulated, and by which engine
- what could not be established, and why

The limitations are part of the report, not an apology at the end of
it. A report that hides its gaps is worse than no report.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field

from app.network_collector import get_network_collector
from app.scenarios_data import SCENARIOS


#: What this tool cannot do, stated plainly.
LIMITATIONS = [
    "Two parts of this report are modelled, not measured: the teaching "
    "routing table, and the scenario networks a packet can be traced "
    "through. Every other section was read from the machine running the "
    "backend. Each evidence item says which it is, and the sections are "
    "titled so the two cannot be confused.",
    "Interfaces, routes and neighbours are read from the machine running "
    "the backend, not from the network the student is exploring.",
    "A packet journey is a simulation against a scenario. No packet left "
    "this machine unless the packet lab was run with root, and even then "
    "it stayed inside isolated namespaces.",
    "A traceroute hop is a device that answered with an ICMP "
    "time-exceeded message. It is a Layer 3 hop, not necessarily the "
    "physical device or the complete path.",
    "A neighbour entry proves a device answered on that link. It does not "
    "prove what cable it is on, or what is between the two ends.",
    "A neighbour's name came from a reverse DNS query, not from the "
    "kernel. The address and its link-layer address are observed; the name "
    "is inferred, and the name's provenance is recorded with it.",
    "Nothing here can discover campus switches, VLANs or cabling. Those "
    "need the network's own inventory.",
]


class EvidenceItem(BaseModel):
    """One piece of evidence, with where it came from."""

    label: str
    value: Any
    source: str = Field(..., description="The command or endpoint it came from")
    provenance: str = Field(..., description="observed, inferred, simulated or unknown")
    collected_at: str
    family: Optional[str] = Field(
        default=None,
        description="The address family this was read from, when it matters",
    )


class ReportSection(BaseModel):
    """A named group of evidence."""

    title: str
    description: str
    evidence: List[EvidenceItem] = Field(default_factory=list)


class Report(BaseModel):
    """A complete report."""

    title: str
    generated_at: str
    machine: str
    sections: List[ReportSection] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)

    def to_markdown(self) -> str:
        """Render the report as Markdown."""
        lines: List[str] = []
        lines.append(f"# {self.title}")
        lines.append("")
        lines.append(f"**Generated:** {self.generated_at}")
        lines.append(f"**Machine:** {self.machine}")
        lines.append("")

        for section in self.sections:
            lines.append(f"## {section.title}")
            lines.append("")
            if section.description:
                lines.append(section.description)
                lines.append("")

            if not section.evidence:
                lines.append("_Nothing was collected for this section._")
                lines.append("")
                continue

            for item in section.evidence:
                value = item.value
                if isinstance(value, (list, tuple)):
                    rendered = ", ".join(str(v) for v in value) if value else "none"
                elif isinstance(value, dict):
                    rendered = json.dumps(value, indent=2, default=str)
                else:
                    rendered = str(value)

                lines.append(f"### {item.label}")
                lines.append("")
                lines.append(f"- **Value:** {rendered}")
                lines.append(f"- **Provenance:** {item.provenance}")
                if item.family:
                    lines.append(f"- **Family:** {item.family}")
                lines.append(f"- **Source:** `{item.source}`")
                lines.append(f"- **Collected:** {item.collected_at}")
                lines.append("")

        lines.append("## Limitations")
        lines.append("")
        for limitation in self.limitations:
            lines.append(f"- {limitation}")
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append(
            "Generated by RouteLens Lite. Every claim above records where it "
            "came from; nothing here is inferred without saying so."
        )
        return "\n".join(lines)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


async def build_report() -> Report:
    """
    Gather what can be measured and assemble a report.

    Failures in collection are recorded as failures, not omitted, so the
    report shows what could not be read as well as what could.
    """
    collector = get_network_collector()
    now = _now()

    sections: List[ReportSection] = []

    # -- The machine's own network -------------------------------------
    network_evidence: List[EvidenceItem] = []

    try:
        interfaces = await collector.collect_interfaces()
        if interfaces.success and interfaces.data:
            for iface in interfaces.data:
                network_evidence.append(
                    EvidenceItem(
                        label=f"Interface {iface.name}",
                        value={
                            "state": iface.state,
                            "mtu": iface.mtu,
                            "mac": iface.mac_address,
                            "ipv4": iface.ipv4_addresses,
                            "ipv6": iface.ipv6_addresses,
                        },
                        source=interfaces.command,
                        provenance="observed",
                        collected_at=interfaces.timestamp,
                    )
                )
        else:
            network_evidence.append(
                EvidenceItem(
                    label="Interfaces",
                    value=interfaces.error or "not collected",
                    source=interfaces.command,
                    provenance="unknown",
                    collected_at=interfaces.timestamp,
                )
            )
    except Exception as exc:
        network_evidence.append(
            EvidenceItem(
                label="Interfaces",
                value=f"collection failed: {exc}",
                source="ip -j addr show",
                provenance="unknown",
                collected_at=now,
            )
        )

    # The kernel keeps the two families in separate tables, so both are read.
    # Reporting only one would make a reader conclude the machine has no
    # IPv6 routes when it does.
    for family in ("ipv4", "ipv6"):
        try:
            routes = await collector.collect_routes(family)
            if routes.success and routes.data:
                for route in routes.data:
                    network_evidence.append(
                        EvidenceItem(
                            label=f"Route {route.destination}",
                            value={
                                "gateway": route.gateway,
                                "interface": route.interface,
                                "metric": route.metric,
                                "protocol": route.proto,
                                "scope": route.scope,
                            },
                            source=routes.command,
                            provenance="observed",
                            collected_at=routes.timestamp,
                            family=family,
                        )
                    )
            else:
                # A table that was read and is empty is not a table that
                # could not be read. Saying so would make a reader think
                # the collection failed.
                network_evidence.append(
                    EvidenceItem(
                        label=f"Routing table ({family})",
                        value=(
                            "no routes in this table"
                            if routes.success
                            else routes.error or "not collected"
                        ),
                        source=routes.command,
                        provenance="observed" if routes.success else "unknown",
                        collected_at=routes.timestamp,
                        family=family,
                    )
                )
        except Exception as exc:
            network_evidence.append(
                EvidenceItem(
                    label=f"Routing table ({family})",
                    value=f"collection failed: {exc}",
                    source=f"ip -j route show ({family})",
                    provenance="unknown",
                    collected_at=now,
                    family=family,
                )
            )

    for family in ("ipv4", "ipv6"):
        try:
            # The names are looked up by the collector; they are useful
            # evidence, so they are kept rather than thrown away. The name
            # is inferred, the address is observed, and the item says which
            # is which.
            neighbors = await collector.collect_neighbors(family)
            if neighbors.success and neighbors.data:
                for neighbor in neighbors.data:
                    network_evidence.append(
                        EvidenceItem(
                            label=f"Neighbour {neighbor.ip_address}",
                            value={
                                "interface": neighbor.interface,
                                "mac": neighbor.mac_address,
                                "state": neighbor.state,
                                "is_router": neighbor.is_router,
                                "hostname": neighbor.hostname,
                                "name_provenance": neighbor.name_provenance,
                                "name_error": neighbor.name_error,
                            },
                            source=neighbors.command,
                            provenance="observed",
                            collected_at=neighbors.timestamp,
                            family=family,
                        )
                    )
            else:
                # As with the routing table: an empty cache that was read
                # successfully is not a cache that could not be read.
                network_evidence.append(
                    EvidenceItem(
                        label=f"Neighbours ({family})",
                        value=(
                            "no neighbours in this cache"
                            if neighbors.success
                            else neighbors.error or "not collected"
                        ),
                        source=neighbors.command,
                        provenance="observed" if neighbors.success else "unknown",
                        collected_at=neighbors.timestamp,
                        family=family,
                    )
                )
        except Exception as exc:
            network_evidence.append(
                EvidenceItem(
                    label=f"Neighbours ({family})",
                    value=f"collection failed: {exc}",
                    source=f"ip -j neigh show ({family})",
                    provenance="unknown",
                    collected_at=now,
                    family=family,
                )
            )

    sections.append(
        ReportSection(
            title="This machine",
            description=(
                "Read directly from the host running the backend. These are "
                "measurements, not examples. The IPv4 and IPv6 tables are "
                "separate in the kernel, so both are reported, and each "
                "item names the family it came from."
            ),
            evidence=network_evidence,
        )
    )

    # -- The simulated teaching table ----------------------------------
    sample_evidence = [
        EvidenceItem(
            label=f"Route {route.prefix}",
            value={
                "next_hop": route.via,
                "interface": route.dev,
                "metric": route.metric,
                "type": route.source,
            },
            source="the sample routing table in the backend",
            provenance="simulated",
            collected_at=now,
        )
        for route in SCENARIOS["client-router-server"].node("router").routes
    ]

    sections.append(
        ReportSection(
            title="The teaching routing table",
            description=(
                "The table the routing analysis works against. It is a worked "
                "example and does not describe any real network."
            ),
            evidence=sample_evidence,
        )
    )

    # -- The scenarios available ----------------------------------------
    scenario_evidence = [
        EvidenceItem(
            label=scenario.title,
            value={
                "id": scenario.id,
                "devices": len(scenario.nodes),
                "links": len(scenario.links),
            },
            source="the scenario definitions in the backend",
            provenance="simulated",
            collected_at=now,
        )
        for scenario in SCENARIOS.values()
    ]

    sections.append(
        ReportSection(
            title="Simulated networks",
            description=(
                "The scenarios a packet can be traced through. Each is a "
                "model, and is labelled as one wherever it appears."
            ),
            evidence=scenario_evidence,
        )
    )

    return Report(
        title="RouteLens Lite — network analysis report",
        generated_at=now,
        machine="the host running the backend",
        sections=sections,
        limitations=LIMITATIONS,
    )
