"""
RouteLens Lite - Routing Models

Defines the data models for routing table entries using Pydantic for validation.
Supports both IPv4 and IPv6.
"""

from dataclasses import dataclass
from enum import Enum
from ipaddress import IPv4Address, IPv4Network, IPv6Address, IPv6Network, IPv4Address, IPv6Address, IPv4Network, IPv6Network
from typing import Optional, Union

from pydantic import BaseModel, Field, field_validator


class Provenance(str, Enum):
    """Provenance of routing information - how was this route determined."""
    OBSERVED = "observed"      # Directly observed from system (ip route, ip neighbor, etc.)
    INFERRED = "inferred"      # Derived from other observed data
    SIMULATED = "simulated"    # Generated by simulation/packet tracing
    UNKNOWN = "unknown"        # Origin unknown or uncertain


class NextHopType(str, Enum):
    """Type of next hop for a routing entry."""

    GATEWAY = "gateway"  # Next hop is a gateway IP address
    DIRECT = "direct"  # Directly connected network (no gateway needed)


class IPVersion(str, Enum):
    """IP version for routing entries."""

    IPV4 = "ipv4"
    IPV6 = "ipv6"


class RoutingEntry(BaseModel):
    """
    A single routing table entry.

    Attributes:
        destination: The destination network in CIDR notation (e.g., "192.168.1.0/24" or "2001:db8::/32")
        next_hop: The next hop IP address (required for gateway type)
        interface: The network interface name (e.g., "eth0")
        metric: Non-negative integer cost metric (lower is better)
        next_hop_type: Whether this is a gateway or direct connection
        provenance: How this route was determined
    """

    destination: str = Field(..., description="Destination network in CIDR notation (e.g., 192.168.1.0/24 or 2001:db8::/32)")
    next_hop: Optional[str] = Field(None, description="Next hop gateway IP address")
    interface: str = Field(..., description="Network interface name (e.g., eth0)")
    metric: int = Field(..., ge=0, description="Non-negative integer metric (lower is better)")
    next_hop_type: NextHopType = Field(NextHopType.GATEWAY, description="Type of next hop: gateway or direct")
    provenance: Provenance = Field(Provenance.UNKNOWN, description="How this route was determined")

    @field_validator("destination")
    @classmethod
    def validate_destination(cls, v: str) -> str:
        """Validate that destination is a valid IPv4 or IPv6 CIDR network."""
        try:
            # Try IPv4 first
            IPv4Network(v, strict=False)
        except ValueError:
            try:
                IPv6Network(v, strict=False)
            except ValueError as e:
                raise ValueError(f"Invalid CIDR notation: {v}") from e
        return v

    @field_validator("next_hop")
    @classmethod
    def validate_next_hop(cls, v: Optional[str]) -> Optional[str]:
        """Validate that next_hop is a valid IPv4 or IPv6 address if provided."""
        if v is not None:
            try:
                IPv4Address(v)
            except ValueError:
                try:
                    IPv6Address(v)
                except ValueError as e:
                    raise ValueError(f"Invalid next hop IP address: {v}") from e
        return v

    @field_validator("interface")
    @classmethod
    def validate_interface(cls, v: str) -> str:
        """Validate that interface is not empty."""
        if not v or not v.strip():
            raise ValueError("Interface name cannot be empty")
        return v.strip()

    @field_validator("metric")
    @classmethod
    def validate_metric(cls, v: int) -> int:
        """Validate that metric is non-negative."""
        if v < 0:
            raise ValueError("Metric must be a non-negative integer")
        return v

    def get_network(self) -> Union[IPv4Network, IPv6Network]:
        """Return the destination as an IPNetwork object (IPv4 or IPv6)."""
        try:
            return IPv4Network(self.destination, strict=False)
        except ValueError:
            return IPv6Network(self.destination, strict=False)

    def get_next_hop(self) -> Optional[Union[IPv4Address, IPv6Address]]:
        """Return the next hop as an IPAddress object if present."""
        if self.next_hop:
            try:
                return IPv4Address(self.next_hop)
            except ValueError:
                return IPv6Address(self.next_hop)
        return None

    def get_ip_version(self) -> IPVersion:
        """Return the IP version of this routing entry."""
        try:
            IPv4Network(self.destination, strict=False)
            return IPVersion.IPV4
        except ValueError:
            return IPVersion.IPV6


class RouteLookupResult(BaseModel):
    """
    Result of a route lookup operation.

    Attributes:
        matched: Whether a matching route was found
        route: The selected routing entry (None if no match)
        explanation: Human-readable explanation of the selection
        error: Error message if input was invalid (None if successful)
        transmitted: Always false; this API performs routing decisions only,
            not actual packet transmission.
    """

    matched: bool
    route: Optional[RoutingEntry] = None
    explanation: str = ""
    error: Optional[str] = None
    transmitted: bool = False


@dataclass
class PacketHop:
    """Represents a single hop in the packet journey."""
    hop_number: int
    current_device: str
    destination_ip: str
    matched_route_destination: Optional[str] = None
    matched_route_next_hop: Optional[str] = None
    matched_route_interface: Optional[str] = None
    matched_route_metric: Optional[int] = None
    next_hop_ip: Optional[str] = None
    egress_interface: Optional[str] = None
    action: str = "forward"  # forward, deliver, drop
    explanation: str = ""


class PacketJourneyRequest(BaseModel):
    """Request model for packet journey trace."""
    source_ip: str = Field(..., description="Source IPv4 or IPv6 address")
    destination_ip: str = Field(..., description="Destination IPv4 or IPv6 address")


class PacketJourneyResponse(BaseModel):
    """Response model for packet journey trace."""
    source_ip: str
    destination_ip: str
    hops: list[dict]
    success: bool
    error: Optional[str] = None


class RouteLookupResult(BaseModel):
    """
    Result of a route lookup operation.

    Attributes:
        matched: Whether a matching route was found
        route: The selected routing entry (None if no match)
        explanation: Human-readable explanation of the selection
        error: Error message if input was invalid (None if successful)
        transmitted: Always false; this API performs routing decisions only,
            not actual packet transmission.
    """

    matched: bool
    route: Optional[RoutingEntry] = None
    explanation: str = ""
    error: Optional[str] = None
    transmitted: bool = False


