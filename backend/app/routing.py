"""
RouteLens Lite - Routing Models

Defines the data models for routing table entries using Pydantic for validation.
Supports both IPv4 and IPv6.
"""

from dataclasses import dataclass
from enum import Enum
from ipaddress import IPv4Address, IPv4Network, IPv6Address, IPv6Network
from typing import Optional, Union

from pydantic import BaseModel, Field, field_validator


class Provenance(str, Enum):
    """Provenance of routing information - how was this route determined."""
    OBSERVED = "observed"      # Directly observed from system (ip route, ip neighbor, etc.)
    INFERRED = "inferred"      # Derived from other observed data
    SIMULATED = "simulated"    # Generated by simulation/packet tracing
    UNKNOWN = "unknown"        # Origin unknown or uncertain


class NextHopType(str, Enum):
    """Type of next hop for a routing entry."""

    GATEWAY = "gateway"  # Next hop is a gateway IP address
    DIRECT = "direct"  # Directly connected network (no gateway needed)


class IPVersion(str, Enum):
    """IP version for routing entries."""

    IPV4 = "ipv4"
    IPV6 = "ipv6"


class RoutingEntry(BaseModel):
    """
    A single routing table entry.

    Attributes:
        destination: The destination network in CIDR notation (e.g., "192.168.1.0/24" or "2001:db8::/32")
        next_hop: The next hop IP address (required for gateway type)
        interface: The network interface name (e.g., "eth0")
        metric: Non-negative integer cost metric (lower is better)
        next_hop_type: Whether this is a gateway or direct connection
        provenance: How this route was determined
    """

    destination: str = Field(..., description="Destination network in CIDR notation (e.g., 192.168.1.0/24 or 2001:db8::/32)")
    next_hop: Optional[str] = Field(None, description="Next hop gateway IP address")
    interface: str = Field(..., description="Network interface name (e.g., eth0)")
    metric: int = Field(..., description="Non-negative integer metric (lower is better)")
    next_hop_type: NextHopType = Field(NextHopType.GATEWAY, description="Type of next hop: gateway or direct")
    provenance: Provenance = Field(Provenance.UNKNOWN, description="How this route was determined")

    @field_validator("destination")
    @classmethod
    def validate_destination(cls, v: str) -> str:
        """Validate the destination and store it in network form.

        A prefix length is required. Without one, "192.168.1.7" would be
        read as a /32 covering exactly one address, and the table would
        show a bare address where every other row shows a network.

        The stored value is the network, so "192.168.1.5/24" is kept as
        "192.168.1.0/24" and the table never shows host bits that do
        not apply.
        """
        if "/" not in v:
            raise ValueError(
                f"Destination must include a prefix length, for example "
                f"192.168.1.0/24. {v} would be read as {v}/32."
            )
        try:
            network = IPv4Network(v, strict=False)
        except ValueError:
            try:
                network = IPv6Network(v, strict=False)
            except ValueError as e:
                raise ValueError(f"Invalid CIDR notation: {v}") from e
        return str(network)

    @field_validator("next_hop")
    @classmethod
    def validate_next_hop(cls, v: Optional[str]) -> Optional[str]:
        """Validate that next_hop is a valid IPv4 or IPv6 address if provided."""
        if v is not None:
            try:
                IPv4Address(v)
            except ValueError:
                try:
                    IPv6Address(v)
                except ValueError as e:
                    raise ValueError(f"Invalid next hop IP address: {v}") from e
        return v

    @field_validator("interface")
    @classmethod
    def validate_interface(cls, v: str) -> str:
        """Validate that interface is not empty."""
        if not v or not v.strip():
            raise ValueError("Interface name cannot be empty")
        return v.strip()

    @field_validator("metric")
    @classmethod
    def validate_metric(cls, v: int) -> int:
        """Validate that metric is non-negative."""
        if v < 0:
            raise ValueError("Metric must be a non-negative integer")
        return v

    def get_network(self) -> Union[IPv4Network, IPv6Network]:
        """Return the destination as an IPNetwork object (IPv4 or IPv6)."""
        try:
            return IPv4Network(self.destination, strict=False)
        except ValueError:
            return IPv6Network(self.destination, strict=False)

    def get_next_hop(self) -> Optional[Union[IPv4Address, IPv6Address]]:
        """Return the next hop as an IPAddress object if present."""
        if self.next_hop:
            try:
                return IPv4Address(self.next_hop)
            except ValueError:
                return IPv6Address(self.next_hop)
        return None

    def get_ip_version(self) -> IPVersion:
        """Return the IP version of this routing entry."""
        try:
            IPv4Network(self.destination, strict=False)
            return IPVersion.IPV4
        except ValueError:
            return IPVersion.IPV6


class RouteLookupResult(BaseModel):
    """
    Result of a route lookup operation.

    Attributes:
        matched: Whether a matching route was found
        route: The selected routing entry (None if no match)
        explanation: Human-readable explanation of the selection
        error: Error message if input was invalid (None if successful)
        transmitted: Always false; this API performs routing decisions only,
            not actual packet transmission.
    """

    matched: bool
    route: Optional[RoutingEntry] = None
    explanation: str = ""
    error: Optional[str] = None
    transmitted: bool = False


# The actions a hop of a packet journey can carry. This is the
# authoritative list; the endpoint docstring and the response model both
# point at it.
#
#   forward             - the router handed the packet to a next hop
#   deliver             - the packet reached the destination
#   drop                - the packet was discarded: no route to the
#                         destination, or the hop limit ran out
#   loop                - the packet came back to a router it had
#                         already been at
#   unresolved_next_hop - the packet was handed to a router whose own
#                         routing table is not part of the table being
#                         traced, so the journey stops there. The packet
#                         was not discarded; it was forwarded
#   error               - the request, or a routing table, could not be
#                         read
PACKET_JOURNEY_ACTIONS = (
    "forward",
    "deliver",
    "drop",
    "loop",
    "unresolved_next_hop",
    "error",
)


@dataclass
class PacketHop:
    """Represents a single hop in the packet journey."""
    hop_number: int
    current_device: str
    destination_ip: str
    matched_route_destination: Optional[str] = None
    matched_route_next_hop: Optional[str] = None
    matched_route_interface: Optional[str] = None
    matched_route_metric: Optional[int] = None
    next_hop_ip: Optional[str] = None
    egress_interface: Optional[str] = None
    # One of PACKET_JOURNEY_ACTIONS.
    action: str = "forward"
    explanation: str = ""


class PacketJourneyRequest(BaseModel):
    """Request model for packet journey trace."""
    source_ip: str = Field(..., description="Source IPv4 or IPv6 address")
    destination_ip: str = Field(..., description="Destination IPv4 or IPv6 address")


class MatchedRoute(BaseModel):
    """
    The route a router selected at one hop of a journey.

    Attributes:
        destination: The network that matched, in CIDR notation
        next_hop: The next hop address, or None for a direct route
        interface: The outgoing interface the packet left by
        metric: The cost of the route
    """

    destination: str
    next_hop: Optional[str] = None
    interface: str
    metric: int


class PacketHopResponse(BaseModel):
    """
    One hop of a packet journey.

    The fields are exactly the ones the interface renders. A field that
    does not apply to this hop is left out of the response entirely,
    rather than sent as null, so the shape of the data says what
    happened.

    Attributes:
        hop_number: Which hop this is, counting from 1
        current_device: The device making the decision at this hop
        destination_ip: The destination the packet is travelling towards
        action: One of PACKET_JOURNEY_ACTIONS
        explanation: A plain-language account of the decision
        matched_route: The route that was selected, when one was
        next_hop_ip: The address the packet was handed to
        egress_interface: The interface the packet left by
    """

    hop_number: int
    current_device: str
    destination_ip: str
    action: str = Field(
        ...,
        description=(
            "What happened at this hop. One of: "
            + ", ".join(PACKET_JOURNEY_ACTIONS)
        ),
    )
    explanation: str
    matched_route: Optional[MatchedRoute] = Field(
        default=None, exclude_if=lambda value: value is None
    )
    next_hop_ip: Optional[str] = Field(
        default=None, exclude_if=lambda value: value is None
    )
    egress_interface: Optional[str] = Field(
        default=None, exclude_if=lambda value: value is None
    )


class PacketJourneyResponse(BaseModel):
    """
    Response model for packet journey trace.

    The journey is worked out from a routing table. No packet is sent,
    so the answer is a calculated decision rather than an observation of
    traffic, and `provenance` says so.

    Attributes:
        source_ip: The address the packet started from
        destination_ip: The address the packet was heading for
        hops: Each forwarding decision, in order
        success: Whether the packet was shown reaching the destination
        error: Why the journey did not reach the destination, if it did not
        provenance: How this answer was arrived at
    """

    source_ip: str
    destination_ip: str
    hops: list[PacketHopResponse]
    success: bool
    error: Optional[str] = None
    provenance: str = Field(
        "simulated",
        description=(
            "How this journey was worked out. 'simulated' because the path is "
            "calculated from a routing table; no packet is transmitted."
        ),
    )


